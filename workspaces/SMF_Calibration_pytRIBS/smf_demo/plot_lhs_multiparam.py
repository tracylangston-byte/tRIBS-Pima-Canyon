def build_response_curve_axes(fig, n):
    """
    Build an (approximately) centred two-row grid of n subplot axes.
    n<=4  -> simple n_top x n_bot grid (2x2 for n=4, single row otherwise)
    n>4   -> top row = ceil(n/2) axes, bottom row = floor(n/2) axes,
             bottom row horizontally centred under the top row.
    This reproduces the hand-built gridspec layouts used in the original
    5-param (2x2), 6-param (3+2), and 11-param (4+3) scripts for any N.
    """
    if n <= 4:
        rows = 2 if n > 2 else 1
        cols = int(np.ceil(n / rows))
        gs = fig.add_gridspec(rows, cols)
        axes = []
        for i in range(n):
            r, c = divmod(i, cols)
            axes.append(fig.add_subplot(gs[r, c]))
        return axes

    top_n   = -(-n // 2)      # ceil(n/2)
    bot_n   = n - top_n
    n_cols  = 2 * top_n
    gs      = fig.add_gridspec(2, n_cols, hspace=0.4, wspace=0.4)
    axes_top = [fig.add_subplot(gs[0, 2 * i:2 * i + 2]) for i in range(top_n)]
    offset   = top_n - bot_n
    axes_bot = [fig.add_subplot(gs[1, 2 * i + offset:2 * i + offset + 2]) for i in range(bot_n)]
    return axes_top + axes_bot


