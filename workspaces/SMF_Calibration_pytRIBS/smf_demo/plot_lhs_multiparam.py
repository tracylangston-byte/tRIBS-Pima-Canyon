"""
plot_lhs_multiparam.py
=======================
Generates all diagnostic figures for an N-parameter LHS sweep (series 80,
81, 82, or 83). Replaces plot_lhs_5param.py, plot_lhs_6param.py, and
plot_lhs_11param.py, which were three copies of the same script with the
swept-parameter list hardcoded differently in each.

Switch series by editing ACTIVE_SERIES below (one line). Everything else
-- which columns are swept, axis labels, output paths, which optional
deep-dive figures to draw -- is driven by the SERIES_PRESETS dict.

Usage (run from the smf_demo directory):
    python plot_lhs_multiparam.py

Produces up to 11 figures saved to:
    calibration_work/03_comparisons/sensitivity_plots/{SERIES_LABEL}/

Core figure list (all series, figs 1-9 identical structure regardless of N):
    fig1_hydrograph_envelope_all.png   -- All runs: envelope + median + best run
    fig2_hydrograph_envelope_kge0.png  -- KGE > 0 runs only + filtered median
    fig3_correlation_bar.png           -- Pearson r of each swept param vs KGE
    fig4_parallel_coordinates.png      -- All N params as vertical axes, colored by KGE
    fig5_pairwise_scatter.png          -- C(N,2)-panel pairwise scatter matrix, colored by KGE
    fig6_kge_vs_each_param.png         -- N-panel KGE vs each parameter (1D response curves)
    fig7_pbias_vs_kge.png              -- PBIAS vs KGE scatter, colored by Ks multiplier
    fig8_top15_table.png               -- Top-15 runs by KGE as formatted table
    fig9_kge_components_vs_ks.png      -- r / alpha / beta each vs Ks, colored by KGE

Optional per-series deep-dive figures (fig10, fig11, ...) are listed in each
preset's "deep_dives" entry and rendered by one of two reusable templates:
    "single_vs_ks_pbias"   -- (a) KGE vs param, colored by Ks
                              (b) param vs Ks, colored by KGE
                              (c) PBIAS vs param, colored by KGE
    "two_param_interaction" -- (a) KGE vs param1, colored by Ks
                               (b) KGE vs param2, colored by Ks
                               (c) param1 x param2, colored by KGE

======================================================================
UPDATED / CONSOLIDATED -- see notes below
======================================================================
This script was generated by merging three near-duplicate files:
    - plot_lhs_5param.py   (series 80 KsLo / 81 KsHi -- 4 swept params)
    - plot_lhs_6param.py   (series 82 -- adds psiB_mult -- 5 swept params)
    - plot_lhs_11param.py  (series 83 -- adds channelwidthcoeff, thetaS_mult
                             -- 7 swept params)
Figures 1-9 in all three source files were already written generically
over a PARAM_META dict, so consolidating them required only generalizing
the fig5 pairwise-panel-count and fig6 subplot-grid layout to work for any
N, and moving each series' specific parameter list/labels into a
SERIES_PRESETS dict. Figures 10/11 (deep-dives) were bespoke per series;
they are now two reusable template functions instead of copy-pasted
per-series blocks.

No metrics were dropped from THIS script's own logic (it never referenced
peak_error_m3s, volume_error_pct, or rmse_m3s -- those are eliminated
project-wide, see build_sensitivity_run.py / run_sensitivity_single.py
metric notes and plot_recession_residual_pca.py, plot_best_run_diagnostic.py,
and plot_sensitivity.py, which did reference them and were updated
separately).

The old files (plot_lhs_5param.py, plot_lhs_6param.py, plot_lhs_11param.py)
should be deleted/archived once this replacement is verified against a
saved figure set from each series.
"""

